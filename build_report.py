"""Builds outputs/report.html (self-contained, opens offline) from the CSV
tables and PNG figures that run_analysis.py writes."""
from __future__ import annotations

import base64
import json
from pathlib import Path

import pandas as pd

OUT = Path(__file__).resolve().parent / "outputs"

CSS = """
body{font-family:system-ui,Segoe UI,Arial,sans-serif;max-width:1050px;margin:24px auto;padding:0 16px;color:#1c2a4a;line-height:1.45}
h1{font-size:1.6rem;margin-bottom:.2rem} h2{margin-top:2.2rem;border-bottom:2px solid #1c2a4a;padding-bottom:4px;font-size:1.2rem}
table{border-collapse:collapse;width:100%;margin:10px 0;font-size:.92rem}
th{background:#1c2a4a;color:#fff;text-align:left;padding:7px 9px} td{padding:6px 9px;border-bottom:1px solid #d9dde6}
tr:nth-child(even) td{background:#f3f5f9} .note{color:#56607a;font-size:.88rem}
img{max-width:100%;border:1px solid #d9dde6;margin:8px 0} code{background:#f3f5f9;padding:1px 5px;border-radius:3px}
.scroll{overflow-x:auto}
"""


def ci(row, key):
    return f"{row[key]:.3f} ({row[key + '_lo']:.3f}–{row[key + '_hi']:.3f})"


def table(df: pd.DataFrame) -> str:
    return '<div class="scroll">' + df.to_html(index=False, border=0, escape=True) + "</div>"


def img(name: str) -> str:
    b64 = base64.b64encode((OUT / "figures" / name).read_bytes()).decode()
    return f'<img alt="{name}" src="data:image/png;base64,{b64}">'


def perf(df: pd.DataFrame, id_cols: list[str], extra: list[str] = ()) -> pd.DataFrame:
    rows = []
    for _, r in df.iterrows():
        row = {c.replace("_", " ").title(): r[c] for c in id_cols}
        row["Records"] = int(r["n"])
        for c in extra:
            row[c.title()] = int(r[c])
        row["AUC (95% CI)"] = ci(r, "auc")
        row["Brier"] = f"{r['brier']:.3f}"
        row["Sensitivity"] = f"{r['sensitivity']:.3f}"
        row["Specificity"] = f"{r['specificity']:.3f}"
        row["Cal. intercept"] = f"{r['cal_intercept']:.3f}"
        row["Cal. slope"] = f"{r['cal_slope']:.3f}"
        rows.append(row)
    return pd.DataFrame(rows)


def build_report() -> Path:
    man = json.loads((OUT / "run_manifest.json").read_text())
    cohorts = pd.read_csv(OUT / "table2_cohorts.csv")
    internal = pd.read_csv(OUT / "table3_internal_cv.csv")
    external = pd.read_csv(OUT / "table4_external.csv")
    sex = pd.read_csv(OUT / "table5_sex_subgroups.csv")

    cohorts.columns = ["Cohort", "Records", "Disease", "Prevalence %", "Median age", "Female n", "Female %"]
    versions = ", ".join(f"{k} {v}" for k, v in man["versions"].items())
    html = f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Cross-Cohort Heart Disease Detection: results</title><style>{CSS}</style></head><body>
<h1>Cross-Cohort Heart Disease Detection: reproducible results</h1>
<p class="note">Generated by <code>run_analysis.py</code> from the four processed UCI Heart Disease files.
Seed {man['seed']} &middot; {man['cv']} CV &middot; {man['bootstrap_resamples']} bootstrap resamples &middot;
threshold {man['threshold']:.2f}<br>{versions}</p>

<h2>Table 2. Cohort composition</h2>{table(cohorts)}

<h2>Figure 1. Predictor missingness by cohort</h2>{img('fig1_missingness.png')}

<h2>Table 3. Repeated cross-validation performance in Cleveland (development)</h2>
{table(perf(internal, ['model']))}

<h2>Table 4. External performance (models frozen after training on Cleveland)</h2>
{table(perf(external, ['model', 'cohort']))}
<p class="note">Calibration intercept: ideal 0 (positive = risk under-predicted). Calibration slope: ideal 1
(below 1 = predictions too extreme).</p>

<h2>Figure 2. ROC curves, portable logistic model</h2>{img('fig2_roc_portable_logistic.png')}
<h2>Figure 3. Calibration curves, portable logistic model</h2>{img('fig3_calibration_portable_logistic.png')}
<h2>Figure 4. Standardized coefficients, portable logistic model</h2>{img('fig4_coefficients_portable_logistic.png')}

<h2>Table 5. Exploratory sex-stratified performance, portable logistic model</h2>
{table(perf(sex, ['evaluation', 'subgroup'], extra=['disease']))}
<p class="note">Exploratory and underpowered: a warning to test further, not proof of bias.
Research prototype only; not for clinical use.</p>
</body></html>"""
    path = OUT / "report.html"
    path.write_text(html, encoding="utf-8")
    return path


if __name__ == "__main__":
    print(build_report())
